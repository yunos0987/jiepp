#!/usr/bin/env python3
"""Generate the jiepp program icon from one drawing.

The drawing below is the source of truth. This script writes

    docs/jiepp-icon.svg    the vector form (for documents)
    src/jiepp/jiepp.ico    the Windows icon linked into jiepp.exe (jiepp.rc)

The icon shows the directive opener {# above an IEC 61131-3 ladder rung
with a normally open contact (--| |--). The colors are those of
docs/jiepp-banner.svg.

Each icon size is drawn separately at 8x and box-filtered down. The 16, 20
and 24 px images are the hand-drawn pixel grids of HAND_DRAWN instead, since
the strokes of the drawing merge at those sizes (at 20 and 24 px, the two
bars of the contact).

Requires Pillow (pip install Pillow). Run from the repository root:

    python tools/make_icon.py          # rewrite both files
    python tools/make_icon.py --check  # exit 1 if either file differs
"""
import argparse
import io
import sys
from pathlib import Path

from PIL import Image, ImageDraw

NAVY = "#0f172a"
AMBER = "#fbbf24"
WHITE = "#f8fafc"
GREEN = "#86efac"

ICO_SIZES = [16, 20, 24, 32, 40, 48, 64, 256]
SUPERSAMPLE = 8
VIEW = 64.0

# The {# glyph is drawn at 0.8 scale, shifted to leave room for the rung.
_GX, _GY, _GS = 6.4, -1.5, 0.8


def _g(x, y):
    return (_GX + _GS * x, _GY + _GS * y)


# Each stroke: (color, width in view units, list of segments). A segment is
# ("L", p0, p1) or ("C", p0, c1, c2, p1); a stroke's segments are contiguous.
STROKES = [
    # {
    (AMBER, 5.5 * _GS, [
        ("C", _g(27, 13), _g(20.5, 13), _g(20, 17), _g(20, 23)),
        ("L", _g(20, 23), _g(20, 27.5)),
        ("C", _g(20, 27.5), _g(20, 30.5), _g(18.5, 32), _g(14.5, 32)),
        ("C", _g(14.5, 32), _g(18.5, 32), _g(20, 33.5), _g(20, 36.5)),
        ("L", _g(20, 36.5), _g(20, 41)),
        ("C", _g(20, 41), _g(20, 47), _g(20.5, 51), _g(27, 51)),
    ]),
    # #
    (WHITE, 5.0 * _GS, [("L", _g(37, 19), _g(34.5, 45))]),
    (WHITE, 5.0 * _GS, [("L", _g(47, 19), _g(44.5, 45))]),
    (WHITE, 5.0 * _GS, [("L", _g(30, 27), _g(51, 27))]),
    (WHITE, 5.0 * _GS, [("L", _g(29, 37), _g(50, 37))]),
    # rung with a normally open contact
    (GREEN, 3.5, [("L", (10, 51), (27, 51))]),
    (GREEN, 3.5, [("L", (37, 51), (54, 51))]),
    (GREEN, 3.5, [("L", (28.5, 45.5), (28.5, 56.5))]),
    (GREEN, 3.5, [("L", (35.5, 45.5), (35.5, 56.5))]),
]

TILE = (2.0, 2.0, 62.0, 62.0, 13.0)  # x0, y0, x1, y1, corner radius

# Pixel grids: ' ' transparent, '.' tile, 'A' brace, 'W' hash, 'G' rung and
# contact.
PIXELS_16 = [
    " .............. ",
    "................",
    "...AA..W..W.....",
    "...A...W..W.....",
    "...A..WWWWWW....",
    "...A...W..W.....",
    "..AA...W..W.....",
    "...A..WWWWWW....",
    "...A...W..W.....",
    "...A...W..W.....",
    "...AA...........",
    ".......G.G......",
    ".GGGGGGG.GGGGGG.",
    ".......G.G......",
    "................",
    " .............. ",
]
PIXELS_20 = [
    " .................. ",
    "....................",
    "....AA...W...W......",
    "....A....W...W......",
    "....A....W...W......",
    "....A..WWWWWWWWW....",
    "....A....W...W......",
    "...AA....W...W......",
    "...AA....W...W......",
    "....A..WWWWWWWWW....",
    "....A....W...W......",
    "....A....W...W......",
    "....A....W...W......",
    "....AA..............",
    "....................",
    "........G..G........",
    ".GGGGGGGG..GGGGGGGG.",
    "........G..G........",
    "....................",
    " .................. ",
]
PIXELS_24 = [
    "  ....................  ",
    " ...................... ",
    "......AAA...............",
    ".....AA....WW...WW......",
    ".....AA....WW...WW......",
    ".....AA....WW...WW......",
    ".....AA..WWWWWWWWWWW....",
    ".....AA..WWWWWWWWWWW....",
    "...AAA.....WW...WW......",
    "...AAA.....WW...WW......",
    ".....AA..WWWWWWWWWWW....",
    ".....AA..WWWWWWWWWWW....",
    ".....AA....WW...WW......",
    ".....AA....WW...WW......",
    ".....AA....WW...WW......",
    "......AAA...............",
    ".........GG..GG.........",
    ".........GG..GG.........",
    ".GGGGGGGGGG..GGGGGGGGGG.",
    ".GGGGGGGGGG..GGGGGGGGGG.",
    ".........GG..GG.........",
    ".........GG..GG.........",
    " ...................... ",
    "  ....................  ",
]
HAND_DRAWN = {len(rows): rows for rows in (PIXELS_16, PIXELS_20, PIXELS_24)}
_PIXEL_COLORS = {".": NAVY, "A": AMBER, "W": WHITE, "G": GREEN}


def _fmt(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def _pt(p):
    return f"{_fmt(p[0])} {_fmt(p[1])}"


def svg_text():
    x0, y0, x1, y1, r = TILE
    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="256" height="256" role="img" aria-labelledby="title">',
        '  <title id="title">jiepp</title>',
        "  <!-- Generated by tools/make_icon.py; edit the drawing there. -->",
        f'  <rect x="{_fmt(x0)}" y="{_fmt(y0)}" width="{_fmt(x1 - x0)}" height="{_fmt(y1 - y0)}" rx="{_fmt(r)}" fill="{NAVY}"/>',
    ]
    for color, width, segs in STROKES:
        d = [f"M{_pt(segs[0][1])}"]
        for seg in segs:
            if seg[0] == "L":
                d.append(f"L{_pt(seg[2])}")
            else:
                d.append(f"C{_pt(seg[2])} {_pt(seg[3])} {_pt(seg[4])}")
        lines.append(
            f'  <path d="{" ".join(d)}" fill="none" stroke="{color}" stroke-width="{_fmt(width)}"'
            ' stroke-linecap="round" stroke-linejoin="round"/>'
        )
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def _flatten(segs):
    pts = [segs[0][1]]
    for seg in segs:
        if seg[0] == "L":
            pts.append(seg[2])
            continue
        p0, c1, c2, p1 = seg[1:]
        for i in range(1, 25):
            t = i / 24
            u = 1 - t
            pts.append((
                u * u * u * p0[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t * t * t * p1[0],
                u * u * u * p0[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t * t * t * p1[1],
            ))
    return pts


def render_pixels(rows):
    img = Image.new("RGBA", (len(rows[0]), len(rows)), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != " ":
                img.putpixel((x, y), Image.new("RGBA", (1, 1), _PIXEL_COLORS[ch]).getpixel((0, 0)))
    return img


def render(size):
    if size in HAND_DRAWN:
        return render_pixels(HAND_DRAWN[size])
    big = size * SUPERSAMPLE
    k = big / VIEW
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    x0, y0, x1, y1, r = TILE
    draw.rounded_rectangle((x0 * k, y0 * k, x1 * k, y1 * k), radius=r * k, fill=NAVY)
    for color, width, segs in STROKES:
        w = width * k
        pts = [(x * k, y * k) for x, y in _flatten(segs)]
        draw.line(pts, fill=color, width=max(1, round(w)), joint="curve")
        rad = w / 2
        for px, py in (pts[0], pts[-1]):
            draw.ellipse((px - rad, py - rad, px + rad, py + rad), fill=color)
    return img.reduce(SUPERSAMPLE)


def ico_bytes():
    images = [render(s) for s in ICO_SIZES]
    buf = io.BytesIO()
    images[-1].save(buf, format="ICO", sizes=[(s, s) for s in ICO_SIZES], append_images=images[:-1])
    return buf.getvalue()


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a generated file differs")
    ap.add_argument("--root", default=".", help="repository root (default: current directory)")
    args = ap.parse_args()
    root = Path(args.root)
    outputs = {
        root / "docs" / "jiepp-icon.svg": svg_text().encode("utf-8"),
        root / "src" / "jiepp" / "jiepp.ico": ico_bytes(),
    }
    stale = [p for p, data in outputs.items() if not p.is_file() or p.read_bytes() != data]
    if args.check:
        for p in stale:
            print(f"make_icon: {p} is out of date", file=sys.stderr)
        return 1 if stale else 0
    for p, data in outputs.items():
        p.write_bytes(data)
        print(f"make_icon: wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
